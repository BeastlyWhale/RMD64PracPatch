#!/usr/bin/env python3

import sys, os
from functools import lru_cache

W, H = 3, 5

# rows top to bottom, bit 2 = leftmost column
GLYPHS = [
    ('0', [7, 5, 5, 5, 7]),
    ('1', [2, 6, 2, 2, 7]),
    ('2', [7, 1, 7, 4, 7]),
    ('3', [7, 1, 3, 1, 7]),
    ('4', [5, 5, 7, 1, 1]),
    ('5', [7, 4, 7, 1, 7]),
    ('6', [7, 4, 7, 5, 7]),
    ('7', [7, 1, 1, 2, 2]),
    ('8', [7, 5, 7, 5, 7]),
    ('9', [7, 5, 7, 1, 7]),
    (':', [0, 2, 0, 2, 0]),
    ('.', [0, 0, 0, 0, 2]),
    ('-', [0, 0, 7, 0, 0]),
    (' ', [0, 0, 0, 0, 0]),
    ('X', [5, 5, 2, 5, 5]),
    ('Y', [5, 5, 2, 2, 2]),
    ('Z', [7, 1, 2, 4, 7]),
    # "PRAC ROM" practice-ROM mark. 'O' is drawn with '0'.
    ('P', [7, 5, 7, 4, 4]),
    ('R', [6, 5, 6, 5, 5]),
    ('A', [2, 5, 7, 5, 5]),
    ('C', [7, 4, 4, 4, 7]),
    ('T', [7, 2, 2, 2, 2]),
    ('H', [5, 5, 7, 5, 5]),
]


def cells(rows):
    s = set()
    for y, r in enumerate(rows):
        for x in range(W):
            if r & (4 >> x):
                s.add((x, y))
    return s


def cover(on):
    """Minimum number of rectangles that exactly covers `on` and nothing else."""
    if not on:
        return []
    idx = {c: i for i, c in enumerate(sorted(on))}
    full = (1 << len(idx)) - 1

    cands = []
    for x in range(W):
        for y in range(H):
            for w in range(1, W - x + 1):
                for h in range(1, H - y + 1):
                    pts = [(x + dx, y + dy) for dx in range(w) for dy in range(h)]
                    if all(p in on for p in pts):
                        m = 0
                        for p in pts:
                            m |= 1 << idx[p]
                        cands.append((m, (x, y, w, h)))
    # drop rectangles whose coverage is a subset of another's
    cands.sort(key=lambda c: -bin(c[0]).count('1'))
    keep = []
    for m, r in cands:
        if not any((m | km) == km for km, _ in keep):
            keep.append((m, r))

    @lru_cache(maxsize=None)
    def best(rem):
        if rem == 0:
            return ()
        # always extend the lowest uncovered cell, which prunes hard
        low = rem & -rem
        out = None
        for m, r in keep:
            if m & low:
                sub = best(rem & ~m)
                if out is None or len(sub) + 1 < len(out):
                    out = (r,) + sub
        return out

    return list(best(full))


ALL = {(x, y) for x in range(W) for y in range(H)}


def main():
    out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                       'src', 'font_rects.h')
    rects, ofs, holes, hofs, report = [], [0], [], [0], []
    for ch, rows in GLYPHS:
        on = cells(rows)
        ink = cover(on)
        if on:
            box = cover(ALL - on)
            use_box = len(box) + 1 < len(ink)
        else:
            box, use_box = [], False
        runs = sum(1 for y, r in enumerate(rows)
                   for x in range(W)
                   if (r & (4 >> x)) and (x == 0 or not (r & (4 >> (x - 1)))))
        if use_box:
            rects.append((0, 0, W, H))
            holes.extend(box)
            report.append((ch, runs, 1 + len(box)))
        else:
            rects.extend(ink)
            report.append((ch, runs, len(ink)))
        ofs.append(len(rects))
        hofs.append(len(holes))

    with open(out, 'w') as f:
        f.write('/* Generated by tools/genfont.py - do not edit. */\n')
        f.write('#ifndef RMD64_FONT_RECTS_H\n#define RMD64_FONT_RECTS_H\n\n')
        f.write('#define GLYPH_COUNT %d\n' % len(GLYPHS))
        f.write('#define GL_COLON  10\n#define GL_DOT    11\n')
        f.write('#define GL_MINUS  12\n#define GL_SPACE  13\n')
        for i, (ch, _) in enumerate(GLYPHS):
            if ch.isalpha():
                f.write('#define GL_%s      %d\n' % (ch, i))
        f.write('\n')
        f.write('/* white rectangles: the ink, or one full cell for a box glyph */\n')
        f.write('static const u8 kGlyphOfs[GLYPH_COUNT + 1] = {%s};\n\n'
                % ', '.join(str(o) for o in ofs))
        f.write('static const u8 kGlyphRect[%d][4] = {\n' % len(rects))
        for x, y, w, h in rects:
            f.write('    {%d, %d, %d, %d},\n' % (x, y, w, h))
        f.write('};\n\n')
        f.write('/* black cut-outs, drawn after every white rectangle */\n')
        f.write('static const u8 kHoleOfs[GLYPH_COUNT + 1] = {%s};\n\n'
                % ', '.join(str(o) for o in hofs))
        f.write('static const u8 kHoleRect[%d][4] = {\n' % max(len(holes), 1))
        for x, y, w, h in holes or [(0, 0, 0, 0)]:
            f.write('    {%d, %d, %d, %d},\n' % (x, y, w, h))
        f.write('};\n\n#endif\n')

    # Self-check: replay what the payload will draw - white rectangles first,
    # then the black cut-outs - and compare with the glyph bitmap. A box-mode
    # glyph that is one hole short would be a wrong digit on screen.
    for gi, (ch, rows) in enumerate(GLYPHS):
        pix = set()
        for x, y, w, h in rects[ofs[gi]:ofs[gi + 1]]:
            pix |= {(x + dx, y + dy) for dx in range(w) for dy in range(h)}
        for x, y, w, h in holes[hofs[gi]:hofs[gi + 1]]:
            pix -= {(x + dx, y + dy) for dx in range(w) for dy in range(h)}
        if pix != cells(rows):
            sys.exit("glyph '%s' does not render back to its bitmap" % ch)

    tot_runs = sum(r for _, r, _ in report)
    tot_rect = sum(c for _, _, c in report)
    print('font: %d glyphs, %d rectangles total (was %d as horizontal runs, '
          '%.0f%% fewer)' % (len(GLYPHS), tot_rect, tot_runs,
                             100.0 * (tot_runs - tot_rect) / tot_runs))
    print('      worst glyph: %d rectangles'
          % max(c for _, _, c in report))


if __name__ == '__main__':
    main()
